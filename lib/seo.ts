/**
 * XML-escape a URL for use in a sitemap <loc>.
 *
 * Next's sitemap serializer interpolates `item.url` straight into the XML with
 * no escaping (see build/webpack/loaders/metadata/resolve-route-data), so a URL
 * carrying a query string with `&` produces a sitemap Google rejects as
 * malformed. Escaping here is the only place it can happen.
 */
export function sitemapUrl(path: string): string {
  return absoluteUrl(path)
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&apos;");
}

export type Crumb = { name: string; path: string };

export function breadcrumbLd(trail: Crumb[]) {
  return {
    "@context": "https://schema.org",
    "@type": "BreadcrumbList",
    itemListElement: trail.map((crumb, i) => ({
      "@type": "ListItem",
      position: i + 1,
      name: crumb.name,
      item: absoluteUrl(crumb.path),
    })),
  };
}

export type Faq = { q: string; a: string };

export function faqLd(faqs: Faq[]) {
  return {
    "@context": "https://schema.org",
    "@type": "FAQPage",
    mainEntity: faqs.map((faq) => ({
      "@type": "Question",
      name: faq.q,
      acceptedAnswer: { "@type": "Answer", text: faq.a },
    })),
  };
}

export type LdListing = {
  id: string;
  title: string;
  price: number | string;
  images?: string[] | null;
  url: string;
};

/**
 * ItemList of listings. Google uses this to understand that a page is a
 * collection of offers rather than a single product, which is what keeps
 * category and landing pages out of the "thin page" bucket.
 */
export function itemListLd({
  name,
  path,
  description,
  items,
}: {
  name: string;
  path: string;
  description?: string;
  items: LdListing[];
}) {
  return {
    "@context": "https://schema.org",
    "@type": "CollectionPage",
    name,
    url: absoluteUrl(path),
    ...(description ? { description } : {}),
    isPartOf: { "@type": "WebSite", name: "KolejSwap", url: APP_URL },
    mainEntity: {
      "@type": "ItemList",
      numberOfItems: items.length,
      itemListElement: items.map((item, i) => ({
        "@type": "ListItem",
        position: i + 1,
        item: {
          "@type": "Product",
          name: item.title,
          url: absoluteUrl(item.url),
          ...(item.images?.[0] ? { image: item.images[0] } : {}),
          offers: {
            "@type": "Offer",
            priceCurrency: "NGN",
            price: Number(item.price).toFixed(2),
            availability: "https://schema.org/InStock",
            url: absoluteUrl(item.url),
          },
        },
      })),
    },
  };
}

