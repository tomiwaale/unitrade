/**
 * Shared SEO primitives.
 *
 * Every page used to re-derive the canonical origin from process.env inline,
 * which made it easy to drift. Import APP_URL / absoluteUrl from here instead.
 */

export const APP_URL =
  process.env.APP_URL?.startsWith("http")
    ? process.env.APP_URL
    : "https://kolejswap.com";

export function absoluteUrl(path = "/"): string {
  if (path.startsWith("http")) return path;
  // The root canonical is the bare origin, so "/" must not add a trailing
  // slash — otherwise the sitemap and the <link rel="canonical"> disagree.
  if (path === "/" || path === "") return APP_URL;
  return `${APP_URL}${path.startsWith("/") ? path : `/${path}`}`;
}

